"""Правило по ключевым корням слов (нижняя планка D1, также признак «найден корень» для слоёв 5 и отбора фрагментов)."""
from __future__ import annotations

import re

from .config import CATS
from .text import for_model

ROOTS: dict[int, str] = {
    102: r"штукатур|откос|маяк|выравнивани\w* стен",
    103: r"плитк|плиточ|керамогранит|мозаик|затирк|облицов|фартук",
    104: r"сантехни|водоснабж|канализац|смесител|унитаз|раковин|радиатор|\bтруб|полотенцесуш|сифон|инсталляц|водонагревател|водопровод",
    105: r"электр|проводк|розетк|выключател|светильник|люстр|штроб|кабел|\bщиток|электрощит",
    106: r"\bобо[ея]|обо[ея]в|поклейк|покраск|окраск|малярн|шпакл|шпатл|грунтов|красить|красим|стеклохолст|\bпокрас",
}
_RX: dict[int, re.Pattern[str]] = {c: re.compile(p) for c, p in ROOTS.items()}


def find_roots(text: str) -> dict[int, bool]:
    """Для каждой категории: найден ли хоть один ключевой корень в тексте."""
    t = for_model(text)
    return {c: bool(_RX[c].search(t)) for c in CATS}


def rule_predict(text: str) -> list[int]:
    """Список категорий, у которых найден ключевой корень."""
    return [c for c, f in find_roots(text).items() if f]
