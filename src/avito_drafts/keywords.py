"""Правило по ключевым корням слов (нижняя планка D1, также признак «найден корень» для слоёв 5 и отбора фрагментов)."""
from __future__ import annotations

import re

from .config import CATS
from .text import for_model

# Словарь сверен со справочником категорий организаторов и ответами ментора (эксперименты C19, C25):
# шпаклёвка — всегда 106; откосы и выравнивание стен — 102; тёплый пол — кандидат и в 104 (водяной), и в 105 (электрический), тип различает судья.
ROOTS: dict[int, str] = {
    102: r"штукатур|откос|выравнива\w* стен|выровня\w* стен",
    103: r"плитк|плиточ|керамогранит|мозаик|затирк|облицов|фартук|кафел",
    104: r"сантехни|водоснабж|канализац|смесител|унитаз|раковин|радиатор|\bтруб|полотенцесуш|сифон|инсталляц|водонагревател|водопровод|стояк|засор|бойлер|отоплен|т[её]пл\w+ пол",
    105: r"электр|проводк|розет|выключател|светильник|люстр|штроб|кабел|\bщиток|щитк|электрощит|освещ|\bузо\b|дифавтомат|автомат(?:ы|ов)\b|т[её]пл\w+ пол",
    106: r"\bобо(?:и|ев|ям|ями|ях)\b|обо[ея]в|поклейк|покраск|окраск|малярн|малярк|шпакл|шпатл|шлифов|грунтов|красить|красим|стеклохолст|\bпокрас",
}
_RX: dict[int, re.Pattern[str]] = {c: re.compile(p) for c, p in ROOTS.items()}


def find_roots(text: str) -> dict[int, bool]:
    """Для каждой категории: найден ли хоть один ключевой корень в тексте."""
    t = for_model(text)
    return {c: bool(_RX[c].search(t)) for c in CATS}


def rule_predict(text: str) -> list[int]:
    """Список категорий, у которых найден ключевой корень."""
    return [c for c, f in find_roots(text).items() if f]
